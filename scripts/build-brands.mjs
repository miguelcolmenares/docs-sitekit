#!/usr/bin/env node
// Generate the brand logos module of the template from the pinned `simple-icons` package.
//
//   node scripts/build-brands.mjs            write the module and the notices
//   node scripts/build-brands.mjs --check    fail when either is out of date
//
// The curated list (scripts/brands/curated.json) names the slugs to ship. Every icon is checked
// against the licence gate: the collection is CC0, but some icons carry their own licence in the
// `license` field. An icon whose licence is not CC0-1.0 fails the script unless it has an entry in
// scripts/brands/allowlist.json that records the licence, the author and the attribution text. Those
// entries are written to the module and to THIRD_PARTY_NOTICES.md.
//
// Options, mostly for tests: --curated, --allowlist, --icons (a JSON file with { version, icons }),
// --out and --notices.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { pathToFileURL } from "node:url";

const ROOT = resolve(import.meta.dirname, "..");
const DEFAULT_LICENSE = "CC0-1.0";
const START = "<!-- brands:start (generated by npm run build:brands, do not edit) -->";
const END = "<!-- brands:end -->";

const defaults = {
  curated: join(ROOT, "scripts", "brands", "curated.json"),
  allowlist: join(ROOT, "scripts", "brands", "allowlist.json"),
  out: join(ROOT, "template", "src", "domain", "brands", "brandData.ts"),
  notices: join(ROOT, "THIRD_PARTY_NOTICES.md"),
};

/** The licence an icon is released under. Simple Icons records one only where it is not the collection's. */
export function licenseOf(icon) {
  return icon.license?.type ?? DEFAULT_LICENSE;
}

/**
 * Apply the licence gate to the curated slugs and return the brands to ship, sorted by slug.
 * Throws one error that lists every problem.
 */
export function curate({ icons, curated, allowlist }) {
  const bySlug = new Map(icons.map((icon) => [icon.slug, icon]));
  const problems = [];
  for (const slug of Object.keys(allowlist)) {
    const entry = allowlist[slug];
    if (!curated.includes(slug))
      problems.push(
        `allowlist.json names "${slug}", which is not in curated.json. Remove the entry.`,
      );
    for (const field of ["license", "author", "attribution"]) {
      if (typeof entry?.[field] !== "string" || entry[field].trim() === "")
        problems.push(`allowlist.json: "${slug}" needs a non-empty "${field}".`);
    }
  }
  const brands = [];
  for (const slug of [...new Set(curated)].sort()) {
    const icon = bySlug.get(slug);
    if (!icon) {
      problems.push(
        `curated.json names "${slug}", which simple-icons does not have in this version.`,
      );
      continue;
    }
    const license = licenseOf(icon);
    const entry = allowlist[slug];
    if (license !== DEFAULT_LICENSE) {
      if (!entry) {
        problems.push(
          `${slug}: the licence is ${license}, not ${DEFAULT_LICENSE}, and "${slug}" is not on scripts/brands/allowlist.json. ` +
            `Read the licence (${icon.license?.url ?? "no url"}), then add an entry with "license", "author" and "attribution", or take it out of curated.json.`,
        );
        continue;
      }
      if (entry.license !== license) {
        problems.push(
          `${slug}: allowlist.json says ${entry.license}, simple-icons says ${license}. Check the licence again and update the entry.`,
        );
        continue;
      }
    }
    brands.push({
      slug,
      title: icon.title,
      path: icon.path,
      license,
      source: icon.source,
      ...(icon.guidelines ? { guidelines: icon.guidelines } : {}),
      ...(license !== DEFAULT_LICENSE
        ? { author: entry.author, attribution: entry.attribution }
        : {}),
    });
  }
  if (problems.length)
    throw new Error(`Brand logos not built:\n${problems.map((p) => `  ${p}`).join("\n")}`);
  return brands;
}

/** The TypeScript module with the curated brands. Plain, stable text, so a re-run leaves no diff. */
export function renderModule(brands, version) {
  const lines = [
    `// Generated by scripts/build-brands.mjs from simple-icons ${version}. Do not edit: run \`npm run build:brands\`.`,
    'import type { Brand } from "./brand";',
    "",
    "/** The brand logos that ship with the kit, sorted by slug. Monochrome path data on a 24 by 24 grid. */",
    "export const BRANDS: readonly Brand[] = [",
  ];
  for (const brand of brands) {
    lines.push("  {");
    for (const [key, value] of Object.entries(brand))
      lines.push(`    ${key}: ${JSON.stringify(value)},`);
    lines.push("  },");
  }
  lines.push("];", "", "/** The version of simple-icons the data above was read from. */");
  lines.push(`export const BRANDS_SOURCE_VERSION = ${JSON.stringify(version)};`, "");
  return lines.join("\n");
}

/** The generated block of THIRD_PARTY_NOTICES.md, markers included. */
export function renderNotices(brands, version) {
  // Spaced the way Prettier writes Markdown, so `format:check` agrees with the generated block.
  const width = Math.max(5, ...brands.map((brand) => brand.title.length));
  const wide = Math.max(7, ...brands.map((brand) => brand.license.length));
  const row = (brand, license) => `| ${brand.padEnd(width)} | ${license.padEnd(wide)} |`;
  const lines = [
    START,
    "",
    "### Brand logos",
    "",
    `The logos in \`template/src/domain/brands/brandData.ts\` are path data from [Simple Icons](https://simpleicons.org) ${version}, ` +
      `a collection released under CC0 1.0. They are copied into the module at build time, so a generated site loads nothing from any host.`,
    "",
    "The marks belong to their owners. Their use here is to name the product or service, and does not suggest endorsement by or " +
      "affiliation with those owners. The collection's [disclaimer](https://github.com/simple-icons/simple-icons/blob/develop/DISCLAIMER.md) " +
      "asks users to check each brand's guidelines before use; the module keeps the `guidelines` and `source` links where Simple Icons has them.",
    "",
    row("Brand", "Licence"),
    `| ${"-".repeat(width)} | ${"-".repeat(wide)} |`,
    ...brands.map((brand) => row(brand.title, brand.license)),
  ];
  const attributed = brands.filter((brand) => brand.attribution);
  if (attributed.length) {
    lines.push("", "Icons with their own licence, each on `scripts/brands/allowlist.json`:", "");
    for (const brand of attributed)
      lines.push(`- ${brand.title}: ${brand.license}, by ${brand.author}. ${brand.attribution}`);
  }
  lines.push("", END);
  return lines.join("\n");
}

/** Put the generated block between its markers. The markers must already be in the file. */
export function spliceNotices(text, block) {
  const start = text.indexOf(START);
  const end = text.indexOf(END);
  if (start === -1 || end === -1 || end < start)
    throw new Error(`The notices file needs the markers ${START} and ${END}.`);
  return text.slice(0, start) + block + text.slice(end + END.length);
}

async function loadIcons(iconsFile) {
  if (iconsFile) return JSON.parse(readFileSync(iconsFile, "utf8"));
  const pinned = JSON.parse(readFileSync(join(ROOT, "package.json"), "utf8")).devDependencies?.[
    "simple-icons"
  ];
  if (!pinned || !/^\d+\.\d+\.\d+$/.test(pinned))
    throw new Error(
      `simple-icons must be pinned to one exact version in package.json, found "${pinned}".`,
    );
  const installed = JSON.parse(
    readFileSync(join(ROOT, "node_modules", "simple-icons", "package.json"), "utf8"),
  ).version;
  if (installed !== pinned)
    throw new Error(
      `simple-icons ${installed} is installed but package.json pins ${pinned}. Run npm install.`,
    );
  const all = await import("simple-icons");
  return {
    version: installed,
    icons: Object.values(all).filter((icon) => icon && typeof icon.slug === "string"),
  };
}

function parseArgs(argv) {
  const options = { check: false };
  for (let index = 0; index < argv.length; index += 1) {
    const flag = argv[index];
    if (flag === "--check") options.check = true;
    else if (["--curated", "--allowlist", "--icons", "--out", "--notices"].includes(flag)) {
      const value = argv[(index += 1)];
      if (!value) throw new Error(`${flag} needs a value.`);
      options[flag.slice(2)] = resolve(value);
    } else throw new Error(`Unknown option ${flag}.`);
  }
  return options;
}

async function main() {
  const options = parseArgs(process.argv.slice(2));
  const paths = {
    ...defaults,
    ...Object.fromEntries(Object.entries(options).filter(([key]) => key in defaults)),
  };
  const { version, icons } = await loadIcons(options.icons);
  const brands = curate({
    icons,
    curated: JSON.parse(readFileSync(paths.curated, "utf8")),
    allowlist: existsSync(paths.allowlist) ? JSON.parse(readFileSync(paths.allowlist, "utf8")) : {},
  });
  const moduleText = renderModule(brands, version);
  const noticesText = spliceNotices(
    readFileSync(paths.notices, "utf8"),
    renderNotices(brands, version),
  );
  const targets = [
    [paths.out, moduleText],
    [paths.notices, noticesText],
  ];
  const stale = targets.filter(
    ([file, text]) => !existsSync(file) || readFileSync(file, "utf8") !== text,
  );
  if (options.check) {
    if (stale.length) {
      console.error(
        `Out of date: ${stale.map(([file]) => file).join(", ")}. Run npm run build:brands.`,
      );
      process.exit(1);
    }
    console.log(`Brand logos are up to date (${brands.length} brands, simple-icons ${version}).`);
    return;
  }
  for (const [file, text] of stale) writeFileSync(file, text);
  console.log(
    `${brands.length} brands from simple-icons ${version}; wrote ${stale.length} file(s).`,
  );
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  main().catch((error) => {
    console.error(error.message);
    process.exit(1);
  });
}
