#!/usr/bin/env node
// Run Lighthouse on a built site, on a phone, and fail when it goes over the budget.
//
//   node scripts/lighthouse.mjs --dist <folder> [--base /widget/] [--runs 3] [--out lighthouse-report]
//   node scripts/lighthouse.mjs --check <report.json> [<report.json> ...]    judge saved reports, run nothing
//
// The site is served by e2e/serve.mjs with --compress, so the sizes are the ones GitHub Pages sends.
// Lighthouse is the public `lighthouse` package, run with npx at the version below. LIGHTHOUSE_BIN points at
// an installed `lighthouse` command instead (a path), for a machine that cannot download it.
// The reports (JSON and HTML, one pair per run) and summary.md go to --out. The worst run of each metric is
// the one judged, so a single slow run fails the job.
import { spawn, spawnSync } from "node:child_process";
import { appendFileSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { get } from "node:http";
import { join, resolve } from "node:path";
import { setTimeout as sleep } from "node:timers/promises";
import { parseArgs } from "node:util";

/** The version of the public package the budget was measured with. Change it, and measure again. */
export const LIGHTHOUSE_VERSION = "12.6.1";

/**
 * What a run may cost, on Lighthouse's mobile preset (a 412 px phone, simulated slow 4G, 4x slower CPU).
 *
 * The values come from three runs of a site generated by `init`, 2026-10-30, with the margin shown:
 *   lcp          measured 1,950 ms   budget 2,500 ms, the "good" limit of Core Web Vitals, 28% of room
 *   cls          measured 0          budget 0.01, the limit the browser test uses; one wrapped line is 0.01 or more
 *   tbt          measured 0 ms       budget 200 ms, the "good" limit; the page has almost no script, so a rise
 *                                    to 200 ms would be a script that was added, not noise
 *   performance  measured 99         budget 95, the score the issue asked for, with four points of room
 */
export const BUDGET = {
  lcp: { label: "Largest Contentful Paint", unit: "ms", max: 2500 },
  cls: { label: "Cumulative Layout Shift", unit: "", max: 0.01 },
  tbt: { label: "Total Blocking Time", unit: "ms", max: 200 },
  performance: { label: "Performance score", unit: "", min: 95 },
};

/** The numbers of one Lighthouse report that the budget is about, and the LCP element for the failure message. */
export function readMetrics(report) {
  const audits = report.audits ?? {};
  const value = (id) => {
    const number = audits[id]?.numericValue;
    if (typeof number !== "number") throw new Error(`The report has no ${id} value`);
    return number;
  };
  const tables = audits["largest-contentful-paint-element"]?.details?.items ?? [];
  const element = tables[0]?.items?.[0]?.node;
  const phases = (tables[1]?.items ?? []).map(
    (item) => `${item.phase} ${Math.round(item.timing)} ms`,
  );
  const score = report.categories?.performance?.score;
  if (typeof score !== "number") throw new Error("The report has no performance score");
  return {
    lcp: value("largest-contentful-paint"),
    cls: value("cumulative-layout-shift"),
    tbt: value("total-blocking-time"),
    performance: Math.round(score * 100),
    lcpElement: element
      ? `${element.selector ?? "?"} "${(element.nodeLabel ?? "").slice(0, 50)}"`
      : "unknown",
    lcpPhases: phases,
  };
}

/** Judge the runs. The worst value of each metric is compared with its limit. Returns rows and `ok`. */
export function judge(runs, budget = BUDGET) {
  const rows = Object.entries(budget).map(([key, limit]) => {
    const values = runs.map((run) => run[key]);
    const worst = "max" in limit ? Math.max(...values) : Math.min(...values);
    const ok = "max" in limit ? worst <= limit.max : worst >= limit.min;
    return {
      key,
      label: limit.label,
      unit: limit.unit,
      values,
      worst,
      limit: limit.max ?? limit.min,
      bound: "max" in limit ? "at most" : "at least",
      ok,
    };
  });
  return { rows, ok: rows.every((row) => row.ok) };
}

const format = (key, number) => (key === "cls" ? number.toFixed(3) : String(Math.round(number)));

/** The result as a Markdown table, for the job summary and the console. */
export function summarize(runs, verdict) {
  const lines = [
    `| Metric | ${runs.map((_, index) => `Run ${index + 1}`).join(" | ")} | Worst | Budget | |`,
    `| --- | ${runs.map(() => "---:").join(" | ")} | ---: | ---: | --- |`,
    ...verdict.rows.map(
      (row) =>
        `| ${row.label} | ${row.values.map((value) => format(row.key, value)).join(" | ")} | ${format(row.key, row.worst)} | ${row.bound} ${format(row.key, row.limit)}${row.unit ? ` ${row.unit}` : ""} | ${row.ok ? "pass" : "FAIL"} |`,
    ),
  ];
  const last = runs[runs.length - 1];
  lines.push(
    "",
    `LCP element: ${last.lcpElement}`,
    `LCP phases: ${last.lcpPhases.join(", ") || "not reported"}`,
  );
  return lines.join("\n");
}

function waitForServer(port, base) {
  return new Promise((resolvePromise, reject) => {
    const started = Date.now();
    const attempt = () =>
      get({ host: "127.0.0.1", port, path: base }, (response) => {
        response.resume();
        resolvePromise();
      }).on("error", async () => {
        if (Date.now() - started > 15000)
          return reject(new Error("The site did not start in 15 s"));
        await sleep(200);
        attempt();
      });
    attempt();
  });
}

function runLighthouse(url, prefix) {
  const bin = process.env.LIGHTHOUSE_BIN;
  const command = bin ?? "npx";
  const args = [
    ...(bin ? [] : ["--yes", `lighthouse@${LIGHTHOUSE_VERSION}`]),
    url,
    "--form-factor=mobile",
    "--only-categories=performance",
    "--output=json",
    "--output=html",
    `--output-path=${prefix}`,
    "--chrome-flags=--headless=new --no-sandbox",
    "--quiet",
  ];
  const result = spawnSync(command, args, {
    encoding: "utf8",
    stdio: ["ignore", "inherit", "inherit"],
  });
  if (result.status !== 0) throw new Error(`lighthouse exited with ${result.status} for ${url}`);
}

async function main() {
  const { values, positionals } = parseArgs({
    options: {
      dist: { type: "string" },
      base: { type: "string", default: "/" },
      runs: { type: "string", default: "3" },
      out: { type: "string", default: "lighthouse-report" },
      port: { type: "string", default: "4410" },
      check: { type: "boolean", default: false },
    },
    allowPositionals: true,
  });

  let runs;
  let out = resolve(values.out);
  if (values.check) {
    if (positionals.length === 0) throw new Error("--check needs at least one report");
    runs = positionals.map((file) => readMetrics(JSON.parse(readFileSync(file, "utf8"))));
  } else {
    if (!values.dist) throw new Error("--dist is required");
    mkdirSync(out, { recursive: true });
    const server = spawn(
      process.execPath,
      [
        join(import.meta.dirname, "..", "e2e", "serve.mjs"),
        "--dist",
        values.dist,
        "--base",
        values.base,
        "--port",
        values.port,
        "--compress",
      ],
      { stdio: "ignore" },
    );
    try {
      await waitForServer(Number(values.port), values.base);
      const count = Number(values.runs);
      for (let index = 1; index <= count; index += 1) {
        runLighthouse(`http://127.0.0.1:${values.port}${values.base}`, join(out, `run-${index}`));
      }
    } finally {
      server.kill();
    }
    runs = readdirSync(out)
      .filter((name) => /^run-\d+\.report\.json$/.test(name))
      .sort()
      .map((name) => readMetrics(JSON.parse(readFileSync(join(out, name), "utf8"))));
  }

  const verdict = judge(runs);
  const text = summarize(runs, verdict);
  console.log(text);
  if (!values.check) writeFileSync(join(out, "summary.md"), `${text}\n`);
  if (process.env.GITHUB_STEP_SUMMARY)
    appendFileSync(process.env.GITHUB_STEP_SUMMARY, `## Lighthouse (mobile)\n\n${text}\n`);
  if (!verdict.ok) {
    const failed = verdict.rows.filter((row) => !row.ok).map((row) => row.label);
    console.error(`\nOver budget: ${failed.join(", ")}.`);
    process.exitCode = 1;
  }
}

if (import.meta.url === `file://${process.argv[1]}`) {
  main().catch((error) => {
    console.error(error.message);
    process.exit(1);
  });
}
